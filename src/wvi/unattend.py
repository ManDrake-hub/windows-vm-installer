"""Generate the autounattend.xml answer file.

The windowsPE pass (language, disk layout, edition, license) runs inside the
headless VM. Windows Setup caches the answer file in C:\\Windows\\Panther, so the
optional specialize-pass commands run later, on the real hardware, during the
first native boot. The oobeSystem pass is left alone: the user goes through the
normal out-of-box experience (account, privacy, network) on the real machine.
"""

from __future__ import annotations

from dataclasses import dataclass
from xml.sax.saxutils import escape

COMPONENT = ('processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" '
             'language="neutral" versionScope="nonSxS"')

# Commands for dual-boot friendliness, run in the specialize pass on the real PC
UTC_CLOCK = ('reg.exe add "HKLM\\SYSTEM\\CurrentControlSet\\Control\\TimeZoneInformation" '
             '/v RealTimeIsUniversal /t REG_DWORD /d 1 /f')
NO_FAST_STARTUP = ('reg.exe add "HKLM\\SYSTEM\\CurrentControlSet\\Control\\Session Manager\\Power" '
                   '/v HiberbootEnabled /t REG_DWORD /d 0 /f')


@dataclass
class AnswerOptions:
    edition: str  # /IMAGE/NAME, e.g. "Windows 11 Pro"
    language: str  # a language present on the ISO, e.g. "it-IT"
    product_key: str = ""  # empty: let Setup pick the edition from /IMAGE/NAME
    accept_eula: bool = False
    efi_size_mb: int = 300
    utc_clock: bool = True
    disable_fast_startup: bool = True


def _commands(opts: AnswerOptions) -> list[str]:
    cmds = []
    if opts.utc_clock:
        cmds.append(UTC_CLOCK)
    if opts.disable_fast_startup:
        cmds.append(NO_FAST_STARTUP)
    return cmds


def build(opts: AnswerOptions) -> str:
    if not opts.accept_eula:
        raise ValueError("the license terms must be accepted by the user before an answer file is built")
    lang = escape(opts.language)
    key = escape(opts.product_key)
    edition = escape(opts.edition)

    specialize = ""
    commands = _commands(opts)
    if commands:
        items = "".join(
            f"""
          <RunSynchronousCommand wcm:action="add">
            <Order>{n}</Order>
            <Path>{escape(cmd)}</Path>
          </RunSynchronousCommand>"""
            for n, cmd in enumerate(commands, 1))
        specialize = f"""
  <settings pass="specialize">
    <component name="Microsoft-Windows-Deployment" {COMPONENT}>
      <RunSynchronous>{items}
      </RunSynchronous>
    </component>
  </settings>"""

    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by windows-vm-installer. The target disk is the only disk in the VM (DiskID 0). -->
<unattend xmlns="urn:schemas-microsoft-com:unattend" xmlns:wcm="http://schemas.microsoft.com/WMIConfig/2002/State">
  <settings pass="windowsPE">
    <component name="Microsoft-Windows-International-Core-WinPE" {COMPONENT}>
      <SetupUILanguage>
        <UILanguage>{lang}</UILanguage>
      </SetupUILanguage>
      <InputLocale>{lang}</InputLocale>
      <SystemLocale>{lang}</SystemLocale>
      <UILanguage>{lang}</UILanguage>
      <UserLocale>{lang}</UserLocale>
    </component>
    <component name="Microsoft-Windows-Setup" {COMPONENT}>
      <DiskConfiguration>
        <Disk wcm:action="add">
          <DiskID>0</DiskID>
          <WillWipeDisk>true</WillWipeDisk>
          <CreatePartitions>
            <CreatePartition wcm:action="add">
              <Order>1</Order>
              <Type>EFI</Type>
              <Size>{int(opts.efi_size_mb)}</Size>
            </CreatePartition>
            <CreatePartition wcm:action="add">
              <Order>2</Order>
              <Type>MSR</Type>
              <Size>16</Size>
            </CreatePartition>
            <CreatePartition wcm:action="add">
              <Order>3</Order>
              <Type>Primary</Type>
              <Extend>true</Extend>
            </CreatePartition>
          </CreatePartitions>
          <ModifyPartitions>
            <ModifyPartition wcm:action="add">
              <Order>1</Order>
              <PartitionID>1</PartitionID>
              <Format>FAT32</Format>
              <Label>System</Label>
            </ModifyPartition>
            <ModifyPartition wcm:action="add">
              <Order>2</Order>
              <PartitionID>3</PartitionID>
              <Format>NTFS</Format>
              <Label>Windows</Label>
              <Letter>C</Letter>
            </ModifyPartition>
          </ModifyPartitions>
        </Disk>
      </DiskConfiguration>
      <ImageInstall>
        <OSImage>
          <InstallFrom>
            <MetaData wcm:action="add">
              <Key>/IMAGE/NAME</Key>
              <Value>{edition}</Value>
            </MetaData>
          </InstallFrom>
          <InstallTo>
            <DiskID>0</DiskID>
            <PartitionID>3</PartitionID>
          </InstallTo>
        </OSImage>
      </ImageInstall>
      <UserData>
        <ProductKey>
          <Key>{key}</Key>
          <WillShowUI>OnError</WillShowUI>
        </ProductKey>
        <AcceptEula>true</AcceptEula>
      </UserData>
    </component>
  </settings>{specialize}
</unattend>
"""
